// Genera src/PokeSave.Core/RegionalDexData.cs con las Pokédex regionales de los juegos
// salvo Espada/Escudo, cuyos números trae PKHeX.
// Fuente: PokéAPI (con caché en tools/.cache). Comprobado contra Bulbapedia: Kalos Centro
// tiene 153 (los 3 singulares van al final), Teselia empieza en 000 (Victini).
// Uso: node tools/build-regional-dex.mjs
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { get, idFromUrl } from './pokeapi.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(here, '..', 'src', 'PokeSave.Core', 'RegionalDexData.cs')

// clave en la web → nombre en PokéAPI
const DEXES = {
  kanto: 'kanto',
  johto: 'original-johto',
  'johto-hgss': 'updated-johto',
  hoenn: 'hoenn',
  'hoenn-oras': 'updated-hoenn',
  sinnoh: 'original-sinnoh',
  'sinnoh-pt': 'extended-sinnoh',
  unova: 'original-unova',
  'unova-b2w2': 'updated-unova',
  'kalos-central': 'kalos-central',
  'kalos-coastal': 'kalos-coastal',
  'kalos-mountain': 'kalos-mountain',
  alola: 'original-alola',
  melemele: 'original-melemele',
  akala: 'original-akala',
  ulaula: 'original-ulaula',
  poni: 'original-poni',
  'alola-usum': 'updated-alola',
  'melemele-usum': 'updated-melemele',
  'akala-usum': 'updated-akala',
  'ulaula-usum': 'updated-ulaula',
  'poni-usum': 'updated-poni',
  'kanto-lgpe': 'letsgo-kanto',
  // Los índices de PKHeX en estos juegos no cuadran (formas regionales, especies que faltan),
  // así que también se usa PokéAPI: Hisui 242, Paldea 400, Arándano 243, Luminalia 232…
  'sinnoh-bdsp': 'original-sinnoh',
  hisui: 'hisui',
  paldea: 'paldea',
  kitakami: 'kitakami',
  blueberry: 'blueberry',
  lumiose: 'lumiose-city',
  hyperspace: 'hyperspace',
}

let body = ''
for (const [key, name] of Object.entries(DEXES)) {
  const dex = await get(`pokedex/${name}`)
  const entries = [...dex.pokemon_entries].sort((a, b) => a.entry_number - b.entry_number)
  const first = entries[0].entry_number
  entries.forEach((e, i) => {
    if (e.entry_number !== first + i) throw new Error(`${name}: números no seguidos en ${e.entry_number}`)
  })
  const species = entries.map((e) => idFromUrl(e.pokemon_species.url))
  body += `        ["${key}"] = new(${first}, [${species.join(', ')}]),\n`
  console.log(`${key.padEnd(16)} ${name.padEnd(18)} ${species.length} (desde ${first})`)
}

const cs = `// <auto-generated>
// Generado por tools/build-regional-dex.mjs desde PokéAPI (https://pokeapi.co). No editar a mano.
// </auto-generated>
namespace PokeSave.Core;

/// <summary>Una Pokédex regional: número del primero y especies (Nacional) en orden.</summary>
internal sealed record RegionalDex(int First, ushort[] Species);

internal static class RegionalDexData
{
    public static readonly IReadOnlyDictionary<string, RegionalDex> Dexes = new Dictionary<string, RegionalDex>
    {
${body}    };
}
`
writeFileSync(OUT, cs)
console.log(`Listo: ${OUT}`)
